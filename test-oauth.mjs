import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
if(!globalThis.crypto)globalThis.crypto=webcrypto;
import worker from './worker.js';
const map=new Map();
const kv={get:async k=>map.get(k)||null,put:async(k,v)=>{map.set(k,v)},delete:async k=>{map.delete(k)}};
const env={DONEXT_KV:kv,DONEXT_AUTH_SECRET:'a'.repeat(40),DONEXT_OAUTH_CLIENT_ID:'coach-test',DONEXT_OAUTH_CLIENT_SECRET:'b'.repeat(40),DONEXT_OAUTH_REDIRECT_URIS:'https://chatgpt.com/aip/test/oauth/callback',ASSETS:{fetch:async()=>new Response('asset')}};
const base='https://donext.test';
const req=(path,method='GET',body=null,headers={})=>worker.fetch(new Request(base+path,{method,headers,body}),env);
const account=await req('/api/auth/email','POST',JSON.stringify({mode:'register',email:'test@example.com',password:'password123'}),{'content-type':'application/json'});
assert.equal(account.status,200);
const login=await account.json();
const verifier='a'.repeat(64);
const b64url=x=>Buffer.from(x).toString('base64url');
const challenge=b64url(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(verifier)));
const fields=new URLSearchParams({response_type:'code',client_id:'coach-test',redirect_uri:'https://chatgpt.com/aip/test/oauth/callback',code_challenge:challenge,code_challenge_method:'S256',state:'xyz',scope:'training:read training:write'});
assert.equal((await req('/oauth/authorize?'+fields)).status,200);
assert.equal((await req('/oauth/authorize?'+new URLSearchParams({...Object.fromEntries(fields),redirect_uri:'https://evil.example/steal'}))).status,400);
const approval=new URLSearchParams(fields);approval.set('email','test@example.com');approval.set('password','password123');approval.set('approve','yes');
const grant=await req('/oauth/authorize','POST',approval,{'content-type':'application/x-www-form-urlencoded'});
assert.equal(grant.status,302);
const code=new URL(grant.headers.get('location')).searchParams.get('code');
const exchange=async(v,c=code)=>req('/oauth/token','POST',new URLSearchParams({grant_type:'authorization_code',client_id:'coach-test',client_secret:'b'.repeat(40),redirect_uri:'https://chatgpt.com/aip/test/oauth/callback',code:c,code_verifier:v}),{'content-type':'application/x-www-form-urlencoded'});
assert.equal((await exchange('b'.repeat(64))).status,400);
const tokens=await exchange(verifier);assert.equal(tokens.status,200);const t=await tokens.json();
assert.equal((await exchange(verifier)).status,400);
const history=await req('/api/history','GET',null,{Authorization:'Bearer '+t.access_token});assert.equal(history.status,200);
const revoke=await req('/api/auth/revoke-coach','POST',null,{Authorization:'Bearer '+login.token});assert.equal(revoke.status,200);
assert.equal((await req('/api/history','GET',null,{Authorization:'Bearer '+t.access_token})).status,401);
const refresh=await req('/oauth/token','POST',new URLSearchParams({grant_type:'refresh_token',client_id:'coach-test',client_secret:'b'.repeat(40),refresh_token:t.refresh_token}));assert.equal(refresh.status,400);
console.log('OAuth local smoke tests passed: registration, redirect allowlist, PKCE, one-time code, history access, revocation, refresh rejection.');
